"""Offline release gate: regenerate both snapshots and compare exact published bytes."""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
with tempfile.TemporaryDirectory(prefix="firetrace-release-") as directory:
    output = Path(directory)
    subprocess.run([sys.executable, str(ROOT / "pipeline/ingest.py")], cwd=ROOT,
                   env={**os.environ, "FIRETRACE_OUTPUT_ROOT": str(output)}, check=True, stdout=subprocess.DEVNULL)
    subprocess.run([sys.executable, str(ROOT / "pipeline/research.py"), "--output-root", str(output)],
                   cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
    generated = [p for p in output.rglob("*") if p.is_file()]
    for file in generated:
        relative = file.relative_to(output)
        assert file.read_bytes() == (ROOT / relative).read_bytes(), f"Generated bytes differ: {relative}"
    digest = hashlib.sha256((ROOT / "src/data/corpus.json").read_bytes()).hexdigest()
    research = json.loads((ROOT / "public/data/research.json").read_text(encoding="utf-8"))
    assert research["base_corpus_sha256"] == digest, "Research does not match actual experiment snapshot"
    print(json.dumps({"generated_files_verified": len(generated), "corpus_sha256": digest,
                      "findings": len(research["findings"]), "research_version": research["dataset_version"]}, indent=2))
